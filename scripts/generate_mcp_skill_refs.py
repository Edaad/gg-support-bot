def _fmt_type(prop: dict) -> str:
    if "type" in prop:
        return str(prop["type"])
    if "anyOf" in prop:
        return "|".join(str(x.get("type", "?")) for x in prop["anyOf"])
    return "any"


def _tool_section(tool, is_write: bool) -> list[str]:
    props = tool.input_schema.get("properties", {})
    required = set(tool.input_schema.get("required", []))
    params = []
    for key, prop in props.items():
        text = f"`{key}` ({_fmt_type(prop)}"
        if "default" in prop:
            text += f", default {json.dumps(prop['default'])}"
        params.append(text + ")")
    lines = [f"### `{tool.name}`" + ("  (write)" if is_write else ""), ""]
    lines.append(textwrap.dedent(tool.description or "").strip())
    lines.append("")
    if params:
        line = "Parameters: " + "; ".join(params)
        if required:
            line += f". Required: {', '.join(sorted(required))}"
        lines += [line + ".", ""]
    return lines


def write_tools_md(tools) -> int:
    by_name = {t.name: t for t in tools}
    groups = list(GROUPS)
    writes = sorted(n for n in by_name if n in WRITE_TOOL_NAMES)
    groups.append(("Write tools (confirm required)", writes))
    covered = {n for _g, names in groups for n in names}
    other = sorted(n for n in by_name if n not in covered)
    if other:
        groups.append(("Other", other))
    out = [
        "# GG Dashboard MCP tool catalogue",
        "",
        "Generated by scripts/generate_mcp_skill_refs.py from the server's tool list. "
        "Every parameter is optional unless listed under *Required*.",
        "",
        "Contents: " + ", ".join(g for g, _ in groups),
        "",
    ]
    for group, names in groups:
        out += [f"## {group}", ""]
        for name in names:
            tool = by_name.get(name)
            if tool is not None:
                out += _tool_section(tool, name in WRITE_TOOL_NAMES)
    (REFS / "tools.md").write_text("\n".join(out))
    return len(tools)


def write_domain_md() -> None:
    parts = [
        "# GG Dashboard domain reference",
        "",
        "Generated by scripts/generate_mcp_skill_refs.py from the server's "
        "reference resources (gg://reference/*).",
        "",
        "Contents: Clubs, Vocabulary, Enumerations, Conventions, Data-quality caveats",
        "",
        resources.clubs_reference().strip(),
        "",
        resources.VOCABULARY.strip(),
        "",
        resources.enums_reference().strip(),
        "",
        resources.CONVENTIONS.strip(),
        "",
        resources.CAVEATS.strip(),
        "",
    ]
    (REFS / "domain.md").write_text("\n".join(parts))


def main() -> int:
    REFS.mkdir(parents=True, exist_ok=True)
    tools = asyncio.run(build_server().list_tools())
    count = write_tools_md(tools)
    write_domain_md()
    print(f"wrote {REFS / 'tools.md'} ({count} tools) and {REFS / 'domain.md'}")
    return 0


